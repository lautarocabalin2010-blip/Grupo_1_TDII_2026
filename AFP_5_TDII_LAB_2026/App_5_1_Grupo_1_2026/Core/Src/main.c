/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_ETH_Init();
  MX_USART3_UART_Init();
  MX_USB_OTG_FS_PCD_Init();

  /* USER CODE BEGIN 2 */

  // 1. Inicializamos la máquina de estados del anti-rebote
  debounceFSM_init();

  // 2. Declaramos y configuramos nuestro retardo modular de 200 ms
  delay_t retardoSecuencia;
  delayInit(&retardoSecuencia, 200);

  uint8_t indice_led = 0;
  uint8_t estado_paso = 0; // 0 = Encender LED, 1 = Apagar LED

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
      debounceFSM_update();

      if (delayRead(&retardoSecuencia) == true)
      {
          if (estado_paso == 0)
          {
              // Encendemos el LED actual
              PrenderLed(Leds[indice_led]);
              estado_paso = 1; // El próximo toque de 200ms toca apagarlo
          }
          else
          {
              // Apagamos el LED actual
              ApagarLed(Leds[indice_led]);
              estado_paso = 0; // El próximo toque de 200ms toca prender el siguiente

              // Avanzamos al siguiente LED del vector
              indice_led++;
              if (indice_led >= Cantidad_Led)
              {
                  indice_led = 0; // Vuelve al LED1 al terminar la ronda
              }
          }
      }
  }
  /* USER CODE END WHILE */
  /* USER CODE BEGIN 3 */
  /* USER CODE END 3 */
}

